# ── Performance Analysis ──────────────────────────────────
import psutil

print(f"{'Qubits':>8} | {'Eve%':>5} | {'Time(s)':>8} | {'Qubits/s':>10} | {'CPU(s)':>8} | {'RAM(MB)':>8}")
